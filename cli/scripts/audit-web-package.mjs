import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,basename} from 'node:path';
const root=resolve(process.argv[2]||'../release');
const raw=JSON.parse(await readFile(resolve(root,'pack.json'),'utf8'));
const entries=Array.isArray(raw)?raw:Object.values(raw);
const pkg=JSON.parse(await readFile('package.json','utf8'));
if(entries.length!==1) throw Error('安装包数量不符');
const entry=entries[0];
if(entry.name!=='@zhicui/cli'||entry.version!==pkg.version||entry.filename!==`zhicui-cli-${pkg.version}.tgz`) throw Error('安装包身份不符');
const docs=new Set(['package.json','README.md','CHANGELOG.md','RELEASE.md']);
if(!entry.files?.some(f=>f.path==='dist/index.js')||entry.files.some(({path})=>!docs.has(path)&&!/^dist\/[a-z-]+\.(?:js|d\.ts)$/.test(path)&&path!=='skills/zhicui/SKILL.md')) throw Error('安装包包含非发行文件');
const bytes=await readFile(resolve(root,basename(entry.filename)));
const sha256=createHash('sha256').update(bytes).digest('hex');
const integrity='sha512-'+createHash('sha512').update(bytes).digest('base64');
if(integrity!==entry.integrity) throw Error('安装包完整性不符');
const manifest={name:entry.name,version:entry.version,filename:entry.filename,bytes:bytes.length,sha256,integrity,commit:process.env.GITHUB_SHA||null,workflow:'publish-zhicui-cli-web.yml',run_id:process.env.GITHUB_RUN_ID||null,source:'https://github.com/kyirexy/zhicui',download_url:`https://luxai.cn/download/cli/${entry.filename}`,node:pkg.engines.node};
await writeFile(resolve(root,'release.json'),JSON.stringify(manifest,null,2)+'\n');
await writeFile(resolve(root,'SHA256SUMS'),`${sha256}  ${entry.filename}\n`);
console.log(JSON.stringify({version:pkg.version,files:entry.files.length,sha256}));
