import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(scriptDir, '..');
const packageJson = JSON.parse(
  readFileSync(join(frontendDir, 'package.json'), 'utf8'),
);

function gitRevision() {
  try {
    return execFileSync(
      'git',
      ['rev-parse', '--short=12', 'HEAD'],
      { cwd: frontendDir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] },
    ).trim();
  } catch {
    return 'development';
  }
}

const builtAt = new Date().toISOString();
const revision = gitRevision();
const explicitId = String(process.env.ZHICUI_WEB_BUILD_ID || '').trim();
const buildId = explicitId || `${revision}-${builtAt.replace(/\D/g, '').slice(0, 14)}`;
const manifest = {
  schema_version: 1,
  build_id: buildId,
  revision,
  version: String(packageJson.version || '0.0.0'),
  built_at: builtAt,
};

const generatedPath = join(frontendDir, 'src', 'generated', 'buildVersion.ts');
mkdirSync(dirname(generatedPath), { recursive: true });
writeFileSync(
  generatedPath,
  [
    '// Generated by scripts/generate-build-version.mjs. Do not edit.',
    `export const CURRENT_WEB_BUILD = ${JSON.stringify(manifest, null, 2)} as const;`,
    '',
  ].join('\n'),
  'utf8',
);

process.stdout.write(`Web build marker: ${buildId}\n`);
